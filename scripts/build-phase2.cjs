/* Reuse the Phase 1 source splitter and offline Mermaid rendering convention. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const {splitSource}=require('./build-reference.cjs');
const root=path.resolve(__dirname,'..');
const escape=value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');

async function build() {
  const course=vm.runInNewContext(fs.readFileSync(path.join(root,'phase2-course.js'),'utf8')+';Phase2Course');
  const mapping={};
  for(const lesson of course.lessons)for(const key of lesson.sources){
    if(mapping[key])throw Error(`Duplicate Phase 2 mapping: ${key}`);
    mapping[key]=[lesson.id];
  }
  // Git may check out Markdown as CRLF on Windows; use a stable logical source.
  const source=fs.readFileSync(path.join(root,'gis-note-phase2.md'),'utf8').replace(/\r\n/g,'\n');
  const sections=splitSource(source,mapping);
  const counts={sections:sections.length,tables:0,codeBlocks:0,diagrams:0};
  const {Marked,Renderer}=await import('marked');
  const renderer=new Renderer(),baseTable=renderer.table;
  let current;
  const diagrams=[];
  renderer.heading=function(token){return `<h2>${this.parser.parseInline(token.tokens)}</h2>\n`;};
  renderer.table=function(token){counts.tables++;return `<div class="source-table" role="region" tabindex="0" aria-label="Table in ${escape(current.title)}">${baseTable.call(this,token)}</div>`;};
  renderer.code=function(token){
    const code=`<pre><code class="language-${escape(token.lang||'text')}">${escape(token.text)}</code></pre>`;
    if(token.lang!=='mermaid'){counts.codeBlocks++;return code;}
    const file=`assets/figures/phase2-${current.id}.svg`;
    if(diagrams.some(d=>d.file===file))throw Error(`Duplicate diagram in ${current.key}`);
    diagrams.push({file,text:token.text,title:current.title});counts.diagrams++;
    return `<figure class="source-diagram"><a href="${file}" target="_blank" rel="noopener noreferrer"><img src="${file}" alt="${escape(current.title)} — source diagram; explanation follows." loading="lazy" decoding="async"></a><figcaption>Source diagram · <a href="${file}" target="_blank" rel="noopener noreferrer">Enlarge ↗</a></figcaption></figure><details class="source-code"><summary>Mermaid diagram definition</summary>${code}</details>`;
  };
  const marked=new Marked({gfm:true,renderer});
  for(const section of sections){current=section;section.html=marked.parse(section.markdown);section.sha256=sha(section.markdown);}
  const {renderMermaid}=await import('@mermaid-js/mermaid-cli');
  const {default:puppeteer}=await import('puppeteer');
  const browser=await puppeteer.launch({headless:true,...(process.env.PUPPETEER_EXECUTABLE_PATH?{executablePath:process.env.PUPPETEER_EXECUTABLE_PATH}:{})});
  try {
    for(const diagram of diagrams){
      const {data}=await renderMermaid(browser,diagram.text,'svg',{fontEmbed:false,backgroundColor:'white',svgId:path.basename(diagram.file,'.svg'),mermaidConfig:{theme:'neutral',fontFamily:'Arial, Helvetica, sans-serif',deterministicIds:true,deterministicIDSeed:diagram.file,flowchart:{htmlLabels:false},class:{htmlLabels:false}}});
      const svg=Buffer.from(data).toString().replace(/<svg\b([^>]*)>/,(match,attrs)=>`<svg${attrs.replace(/\saria-labelledby="[^"]*"/g,'')} aria-labelledby="phase2-title phase2-desc"><title id="phase2-title">${escape(diagram.title)}</title><desc id="phase2-desc">Rendered from the complete diagram definition in gis-note-phase2.md. The adjacent source reading explains how to read this diagram.</desc>`);
      fs.writeFileSync(path.join(root,diagram.file),svg+'\n');
    }
  } finally {await browser.close();}
  const data={source:'gis-note-phase2.md',sourceSha256:sha(source),counts,sections};
  fs.writeFileSync(path.join(root,'phase2-data.js'),'/* Generated by scripts/build-phase2.cjs; preserve the supplied source note. */\nconst Phase2Data = '+JSON.stringify(data)+';\n');
  const directory=path.join(root,'exercises/phase2');fs.mkdirSync(directory,{recursive:true});
  const section=key=>sections.find(s=>s.key===key);
  const block=(key,lang)=>{const match=section(key).markdown.match(new RegExp('```'+lang+'\\r?\\n([\\s\\S]*?)\\r?\\n```'));if(!match)throw Error(`Missing ${lang} in ${key}`);return match[1].replace(/\r\n/g,'\n')+'\n';};
  fs.writeFileSync(path.join(directory,'parcels.geojson'),block('5.1','json'));
  fs.writeFileSync(path.join(directory,'make_dem.py'),block('5.6','python'));
  const sample=block('exercise-4','text').trim();
  if(!/^[0-9a-f]+$/i.test(sample))throw Error('Malformed sample blob');
  fs.writeFileSync(path.join(directory,'sample_polygon.hex'),sample+'\n');
  fs.mkdirSync(path.join(directory,'solutions'),{recursive:true});
  for(const exercise of course.exercises){
    fs.writeFileSync(path.join(directory,`exercise-${exercise.number}.md`),section(`exercise-${exercise.number}`).markdown);
    fs.writeFileSync(path.join(directory,'solutions',`exercise-${exercise.number}.md`),'# Source solution (read the correction notes first)\n\n'+section(`solution-${exercise.number}`).markdown);
  }
  fs.writeFileSync(path.join(root,'PHASE2-COVERAGE.md'),`# Phase 2 source coverage\n\nAll ${counts.sections} sections of [the supplied note](gis-note-phase2.md) are retained without content edits (line endings canonicalised to LF for cross-platform checks). ${counts.tables} tables, ${counts.codeBlocks} code/text blocks and ${counts.diagrams} Mermaid diagrams are rendered offline.\n\nSHA-256 of LF source: \`${data.sourceSha256}\`\n\nReading clarifications and corrected downloadable helpers are separate from the verbatim source. These are content-coverage checks, not certification of GDAL command execution or INSPIRE conformity.\n\n| Source section | Guided chapter | Full reading | Source lines |\n|---|---|---|---|\n${sections.map(s=>`| ${s.title.replace(/\|/g,'\\|')} | [${course.lessons.find(l=>l.id===s.topics[0]).short}](index.html#phase2/lesson/${s.topics[0]}) | [Read](index.html#phase2/reference/${s.id}) | ${s.lineStart}–${s.lineEnd} |`).join('\n')}\n\nRebuild with \`npm run build:phase2\` using Chromium as described in README.md. The deployed static site needs no build or browser process.\n`);
  console.log('Built Phase 2:',counts);
}
if(require.main===module)build().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={build};
